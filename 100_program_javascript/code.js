var daftar = document.getElementById("daftar");
var cari = document.getElementById("cari");
var jumlah = document.getElementById("jumlah");
var atasLagi = document.getElementById("atasLagi");

function tampilkan(data) {
  daftar.innerHTML = "";
  jumlah.textContent = data.length + " program";

  if (data.length == 0) {
    daftar.innerHTML = '<div class="kosong">Program tidak ketemu.</div>';
    return;
  }

  for (var i = 0; i < data.length; i++) {
    var item = data[i];
    var link = document.createElement("a");
    link.className = "kartu";
    link.href = item.folder + "/index.html";

    link.innerHTML = '<span class="nomor">' + item.nomor + '</span>' +
      '<span class="judul">' + item.judul + '</span>' +
      '<span class="folder">' + item.folder + '</span>';

    daftar.appendChild(link);
  }
}

cari.onkeyup = function () {
  var kata = cari.value.toLowerCase();
  var hasil = program.filter(function (item) {
    return item.judul.toLowerCase().indexOf(kata) != -1 || item.folder.toLowerCase().indexOf(kata) != -1;
  });
  tampilkan(hasil);
};

atasLagi.onclick = function () {
  window.scrollTo(0, 0);
};

tampilkan(program);
